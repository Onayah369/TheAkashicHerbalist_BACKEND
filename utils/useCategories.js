function categorizeUses(traditionalUses = []) {
    const categories = new Set();

    for (const useEntry of traditionalUses) {
        const useText = useEntry.use?.toLowerCase() || "";

        for (const [category, keywords] of Object.entries(USE_CATEGORIES)) {
            const matchesCategory = keywords.some((keyword) => 
                useText.includes(keyword.toLowerCase())
            );

            if (matchesCategory) {
                categories.add(category);
            }
        }
    }

    return [...categories].sort();
}

